"""Writes the number words and month names the reader knows, one file per language
(``suveryn_harness/lang/<lang>.numbers.json``), from the standard spelling rules, not typed by hand: num2words for
numbers in words, Babel (Unicode CLDR) for month names.
Also writes the numbers the reader is held to (``tests/spelled_numbers.json``): the standard's spelling of a sample
of numbers, which ``test_reading.py`` reads back.

A tool for a developer, run when a language is added; the harness doesn't need these libraries to run. They are
pinned (``requirements.txt``), so the files can be made again and compared (``--check``):

    uvx --with-requirements packages/harness/tools/requirements.txt python packages/harness/tools/number_words.py

Per language: every number under a thousand as written ("drieëntwintig", "quatre-vingt-dix", "two hundred and five"),
the words a number is written with that are no number alone ("vingts"), the words for a hundred, a thousand, a
million and a milliard, and the months' names, full and short. Keys are as
``values.fold`` folds a word, without spaces and hyphens. What a deed writes otherwise than the standard is added
here by rule (``variants``), never in the reader.
"""
from __future__ import annotations

import json
import random
import re
import sys
import unicodedata
from pathlib import Path

from babel.dates import get_month_names
from num2words import num2words

HARNESS = Path(__file__).resolve().parents[1]
# A language of suveryn_playbooks.LANGUAGES, and the standard's variants spelled into its file: Belgian and Swiss
# French count "septante". A language without a line here has no file, and tests/test_language.py says so.
LANGUAGES = {"nl": ["nl"], "fr": ["fr", "fr_BE", "fr_CH"], "en": ["en"]}


# Words between the parts of a number ("vingt et un", "two hundred and five"): the reader knows them as joins.
JOINS = {"en", "et", "and"}


def fold(word: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFKD", word.casefold()) if not unicodedata.combining(c))


def key(words: str) -> str:
    return re.sub(r"[\s,\-]+", "", fold(words))


def variants(k: str) -> set[str]:
    """How deeds write a number otherwise than the standard: French "cent" and "vingt" with or without their plural s
    ("deux cent mille", "quatre-vingts"), English without "and" ("two hundred five")."""
    out = {k, k.replace("cents", "cent"), k.replace("vingts", "vingt"), re.sub(r"cent(?!s)$", "cents", k)}
    return out | {v.replace("and", "") for v in out if "hundredand" in v}


def last_word(spelled: str) -> str:
    return re.split(r"[\s\-]+", fold(spelled))[-1]


def table(locales: list[str]) -> dict:
    numbers: dict[str, int] = {}
    parts: set[str] = set()
    scales: dict[str, int] = {}
    months: dict[str, int] = {}
    for locale in locales:
        for n in range(1000):
            written = num2words(n, lang=locale)
            for k in variants(key(written)):
                numbers.setdefault(k, n)
            parts |= {v for word in re.split(r"[\s\-]+", fold(written)) for v in variants(word)}
        for value in (100, 10**3, 10**6, 10**9):
            scales.setdefault(last_word(num2words(value, lang=locale)), value)
            many = num2words(2 * value, lang=locale)
            if re.search(r"[\s\-]", many):  # "deux cents", "deux millions"; Dutch "tweehonderd" is one word
                scales.setdefault(last_word(many), value)
        if "mille" in scales:
            scales.setdefault("mil", 1000)  # a year in a French deed: "mil neuf cent nonante-huit"
        for width in ("wide", "abbreviated"):
            for month, name in get_month_names(width, locale=locale).items():
                months.setdefault(fold(name).rstrip("."), month)
    parts -= set(numbers) | set(scales) | JOINS
    return {"numbers": dict(sorted(numbers.items())), "parts": sorted(parts), "scales": dict(sorted(scales.items())), "months": dict(sorted(months.items()))}


def spelled() -> list[dict]:
    """The numbers the reader is held to: every number to 200, and a fixed sample up to two million, per variant."""
    random.seed(20261110)
    sample = list(range(2, 200)) + sorted(random.sample(range(200, 10000), 150)) + sorted(random.sample(range(10000, 2000000), 150))
    return [{"language": language, "number": n, "written": num2words(n, lang=locale)}
            for language, locales in LANGUAGES.items() for locale in locales for n in sample]


def files() -> dict[Path, str]:
    """Every file this tool writes, with its text."""
    about = "Generated by packages/harness/tools/number_words.py from num2words and Unicode CLDR; not edited by hand."
    out = {HARNESS / "src" / "suveryn_harness" / "lang" / f"{language}.numbers.json":
           json.dumps({"_about": about, **table(locales)}, ensure_ascii=False, indent=0) + "\n"
           for language, locales in LANGUAGES.items()}
    cases = {"_about": "Numbers as the standard spells them (packages/harness/tools/number_words.py), which the reader reads back "
                       "(test_reading.py). Generated; not edited by hand.", "cases": spelled()}
    out[HARNESS / "tests" / "spelled_numbers.json"] = json.dumps(cases, ensure_ascii=False, indent=0) + "\n"
    return out


if __name__ == "__main__":
    stale = 0
    for path, text in files().items():
        if "--check" in sys.argv:
            same = path.exists() and path.read_text(encoding="utf-8") == text
            stale += not same
            print(("same    " if same else "DIFFERS ") + str(path.relative_to(HARNESS)))
        else:
            path.write_text(text, encoding="utf-8")
            print("written " + str(path.relative_to(HARNESS)))
    sys.exit(1 if stale else 0)
